// fakeTuner is a fake HDHomeRun whose tuner status can be changed by a
// test to simulate busy tuners.
type fakeTuner struct {
	*httptest.Server
	mu     sync.Mutex
	status []hdhomerun.TunerStatus
}

func (f *fakeTuner) setStatus(st []hdhomerun.TunerStatus) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.status = st
}

// fakeHDHomeRun serves discover.json, lineup.json, status.json and a
// /auto/vN endpoint that emits a live MPEG-2 / AC-3 transport stream
// generated by ffmpeg, which is what a real tuner produces for ATSC 1.0.
func fakeHDHomeRun(t *testing.T, ffmpeg string) *fakeTuner {
	t.Helper()
	f := &fakeTuner{status: []hdhomerun.TunerStatus{{Resource: "tuner0"}, {Resource: "tuner1"}}}
	var srv *httptest.Server
	mux := http.NewServeMux()
	mux.HandleFunc("/discover.json", func(w http.ResponseWriter, r *http.Request) {
		_ = json.NewEncoder(w).Encode(hdhomerun.Device{
			FriendlyName: "Fake HDHomeRun", ModelNumber: "HDHR5-2US", FirmwareVersion: "20240101",
			DeviceID: "FAKE0001", BaseURL: srv.URL, LineupURL: srv.URL + "/lineup.json", TunerCount: 2,
		})
	})
	mux.HandleFunc("/lineup.json", func(w http.ResponseWriter, r *http.Request) {
		_ = json.NewEncoder(w).Encode([]hdhomerun.Channel{
			{GuideNumber: "5.1", GuideName: "TEST-HD", HD: 1, URL: srv.URL + "/auto/v5.1"},
			{GuideNumber: "7.1", GuideName: "LOCKED", DRM: 1, URL: srv.URL + "/auto/v7.1"},
		})
	})
	mux.HandleFunc("/status.json", func(w http.ResponseWriter, r *http.Request) {
		f.mu.Lock()
		defer f.mu.Unlock()
		_ = json.NewEncoder(w).Encode(f.status)
	})
	mux.HandleFunc("/auto/v5.1", func(w http.ResponseWriter, r *http.Request) {
		cmd := exec.CommandContext(r.Context(), ffmpeg,
			"-hide_banner", "-loglevel", "error", "-re",
			"-f", "lavfi", "-i", "testsrc2=size=640x360:rate=30",
			"-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000",
			"-c:v", "mpeg2video", "-b:v", "2000k", "-g", "15",
			"-c:a", "ac3", "-b:a", "192k",
			"-f", "mpegts", "-")
		out, err := cmd.StdoutPipe()
		if err != nil {
			http.Error(w, err.Error(), 500)
			return
		}
		cmd.Stderr = os.Stderr
		if err := cmd.Start(); err != nil {
			http.Error(w, err.Error(), 500)
			return
		}
		defer func() { _ = cmd.Wait() }()
		w.Header().Set("Content-Type", "video/mp2t")
		fl, _ := w.(http.Flusher)
		buf := make([]byte, 32*1024)
		for {
			n, rerr := out.Read(buf)
			if n > 0 {
				if _, werr := w.Write(buf[:n]); werr != nil {
					return
				}
				if fl != nil {
					fl.Flush()
				}
			}
			if rerr != nil {
				return
			}
		}
	})
	srv = httptest.NewServer(mux)
	t.Cleanup(srv.Close)
	f.Server = srv
	return f
}

// testStack is a fake tuner, a registry, a stream manager with the reaper
// running, and the API server in front of them.
type testStack struct {
	hdhr    *fakeTuner
	reg     *tuner.Registry
	streams *stream.Manager
	api     *httptest.Server
}

func newTestStack(t *testing.T, idle, viewerTimeout time.Duration) *testStack {
	t.Helper()
	if testing.Short() {
		t.Skip("short mode")
	}
	ffmpeg, err := stream.FindFFmpeg("")
	if err != nil {
		t.Skip("ffmpeg not installed")
	}
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	hdhr := fakeHDHomeRun(t, ffmpeg)

	client := hdhomerun.NewClient(5 * time.Second)
	reg := tuner.NewRegistry(client, []string{hdhr.URL}, false, log)
	if err := reg.Refresh(context.Background()); err != nil {
		t.Fatalf("refresh: %v", err)
	}
	if got := len(reg.Channels()); got != 2 {
		t.Fatalf("channels = %d, want 2", got)
	}

	streams, err := stream.NewManager(stream.Config{
		FFmpegPath:     ffmpeg,
		BufferDir:      t.TempDir(),
		Encoder:        stream.EncoderSoftware,
		SegmentSeconds: 1,
		WindowSegments: 30,
		IdleTimeout:    idle,
		ReadyTimeout:   40 * time.Second,
		ViewerTimeout:  viewerTimeout,
		VideoBitrateK:  1200,
		AudioBitrateK:  96,
		Deinterlace:    true,
	}, reg, log)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(streams.StopAll)
	ctx, cancel := context.WithCancel(context.Background())
	t.Cleanup(cancel)
	go streams.Reap(ctx)

	caps := stream.Capabilities{FFmpegPath: ffmpeg, Encoder: stream.EncoderSoftware}
	api := httptest.NewServer(New(Deps{
		Registry: reg, Streams: streams, Client: client, Caps: caps,
		Hosts: []string{hdhr.URL}, WebDir: t.TempDir(), Version: "test", Log: log,
	}).Handler())
	t.Cleanup(api.Close)
	return &testStack{hdhr: hdhr, reg: reg, streams: streams, api: api}
}

func postJSON(t *testing.T, url string, body any) (*http.Response, []byte) {
	t.Helper()
	var buf bytes.Buffer
	_ = json.NewEncoder(&buf).Encode(body)
	res, err := http.Post(url, "application/json", &buf)
	if err != nil {
		t.Fatal(err)
	}
	data, _ := io.ReadAll(res.Body)
	res.Body.Close()
	return res, data
}

func TestEndToEndLiveStream(t *testing.T) {
	st := newTestStack(t, time.Minute, 0)
	api := st.api

	// Lineup over the API.
	res, err := http.Get(api.URL + "/api/channels")
	if err != nil || res.StatusCode != 200 {
		t.Fatalf("channels: %v %v", err, res)
	}
	var chans []tuner.Channel
	_ = json.NewDecoder(res.Body).Decode(&chans)
	res.Body.Close()
	if chans[0].GuideNumber != "5.1" || !chans[1].DRM {
		t.Fatalf("unexpected lineup %+v", chans)
	}

	// DRM channel is refused without touching a tuner.
	res, _ = http.Get(api.URL + "/api/channels/7.1/stream/index.m3u8")
	if res.StatusCode != http.StatusBadGateway {
		t.Fatalf("DRM channel status = %d", res.StatusCode)
	}
	res.Body.Close()

	// Unknown channel is a 404.
	res, _ = http.Get(api.URL + "/api/channels/99.9/stream/index.m3u8")
	if res.StatusCode != http.StatusNotFound {
		t.Fatalf("unknown channel status = %d", res.StatusCode)
	}
	res.Body.Close()

	// First playlist request tunes and transcodes.
	start := time.Now()
	res, err = http.Get(api.URL + "/api/channels/5.1/stream/index.m3u8")
	if err != nil {
		t.Fatal(err)
	}
	body, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if res.StatusCode != 200 {
		t.Fatalf("playlist status = %d: %s", res.StatusCode, body)
	}
	t.Logf("first playlist after %s:\n%s", time.Since(start).Round(time.Millisecond), body)
	if ct := res.Header.Get("Content-Type"); ct != "application/vnd.apple.mpegurl" {
		t.Errorf("playlist content-type = %q", ct)
	}
	if !strings.Contains(string(body), "#EXTINF") {
		t.Fatalf("playlist has no segments")
	}
	seg := regexp.MustCompile(`seg_\d{6}\.ts`).FindString(string(body))
	if seg == "" {
		t.Fatalf("no segment name in playlist")
	}

	// Segment is served from the ring buffer.
	res, err = http.Get(api.URL + "/api/channels/5.1/stream/" + seg)
	if err != nil {
		t.Fatal(err)
	}
	n, _ := io.Copy(io.Discard, res.Body)
	res.Body.Close()
	if res.StatusCode != 200 || n < 1000 {
		t.Fatalf("segment %s: status %d, %d bytes", seg, res.StatusCode, n)
	}
	if ct := res.Header.Get("Content-Type"); ct != "video/mp2t" {
		t.Errorf("segment content-type = %q", ct)
	}

	// Path traversal and junk names are rejected.
	res, _ = http.Get(api.URL + "/api/channels/5.1/stream/..%2Findex.m3u8")
	if res.StatusCode == 200 {
		t.Errorf("traversal should not be served")
	}
	res.Body.Close()

	// A second viewer shares the same session: still exactly one stream.
	res, _ = http.Get(api.URL + "/api/channels/5.1/stream/index.m3u8")
	res.Body.Close()
	res, _ = http.Get(api.URL + "/api/streams")
	var sts []stream.Status
	_ = json.NewDecoder(res.Body).Decode(&sts)
	res.Body.Close()
	if len(sts) != 1 || sts[0].Channel != "5.1" || !sts[0].Running {
		t.Fatalf("streams = %+v", sts)
	}

	// Release winds the idle clock forward; with the reaper running the
	// tuner would be freed within seconds. Here we only check it is accepted.
	res, _ = http.Post(api.URL+"/api/channels/5.1/stream/release", "", nil)
	res.Body.Close()
	if res.StatusCode != http.StatusNoContent {
		t.Errorf("release status = %d", res.StatusCode)
	}

	// Stop tears the session down and segments vanish.
	req, _ := http.NewRequest(http.MethodDelete, api.URL+"/api/streams/5.1", nil)
	res, _ = http.DefaultClient.Do(req)
	res.Body.Close()
	res, _ = http.Get(api.URL + "/api/channels/5.1/stream/" + seg)
	res.Body.Close()
	if res.StatusCode != http.StatusNotFound {
		t.Errorf("segment after stop = %d, want 404", res.StatusCode)
	}
}

// TestViewersJoinHeartbeatLeave covers the viewer handle lifecycle: join
// starts the session and returns a handle, heartbeats keep it, leaving
// as the last viewer releases the tuner within seconds, and a handle that
// stops heartbeating expires on its own.
func TestViewersJoinHeartbeatLeave(t *testing.T) {
	st := newTestStack(t, time.Minute, 2*time.Second)
	api := st.api

	res, body := postJSON(t, api.URL+"/api/watch", map[string]any{"channel": "5.1", "name": "Living room"})
	if res.StatusCode != 200 {
		t.Fatalf("watch status = %d: %s", res.StatusCode, body)
	}
	var joined struct {
		ViewerID string `json:"viewerId"`
		Playlist string `json:"playlist"`
	}
	_ = json.Unmarshal(body, &joined)
	if joined.ViewerID == "" || !strings.HasSuffix(joined.Playlist, "/index.m3u8") {
		t.Fatalf("unexpected join response %s", body)
	}

	// Second device joins with its own handle; both show on the stream.
	res, body = postJSON(t, api.URL+"/api/watch", map[string]any{"channel": "5.1", "viewerId": "phone-1", "name": "Phone"})
	if res.StatusCode != 200 {
		t.Fatalf("second watch status = %d: %s", res.StatusCode, body)
	}
	res, _ = http.Get(api.URL + "/api/streams")
	var sts []stream.Status
	_ = json.NewDecoder(res.Body).Decode(&sts)
	res.Body.Close()
	if len(sts) != 1 || len(sts[0].Viewers) != 2 {
		t.Fatalf("streams = %+v, want one session with two viewers", sts)
	}
	res, _ = http.Get(api.URL + "/api/viewers")
	var viewers []stream.Viewer
	_ = json.NewDecoder(res.Body).Decode(&viewers)
	res.Body.Close()
	if len(viewers) != 2 || viewers[0].Name != "Living room" || viewers[0].Addr == "" {
		t.Fatalf("viewers = %+v", viewers)
	}

	// Heartbeat with paused state is recorded; an unknown handle is 404.
	res, _ = postJSON(t, api.URL+"/api/watch/phone-1/heartbeat", map[string]any{"paused": true})
	if res.StatusCode != http.StatusNoContent {
		t.Fatalf("heartbeat status = %d", res.StatusCode)
	}
	res, _ = postJSON(t, api.URL+"/api/watch/nobody/heartbeat", map[string]any{})
	if res.StatusCode != http.StatusNotFound {
		t.Fatalf("unknown heartbeat status = %d", res.StatusCode)
	}
	for _, v := range st.streams.Viewers() {
		if v.ID == "phone-1" && !v.Paused {
			t.Errorf("phone-1 should be paused")
		}
	}

	// The first viewer leaves; the phone keeps the session alive.
	res, _ = postJSON(t, api.URL+"/api/watch/"+joined.ViewerID+"/leave", nil)
	if res.StatusCode != http.StatusNoContent {
		t.Fatalf("leave status = %d", res.StatusCode)
	}
	time.Sleep(1500 * time.Millisecond)
	if _, ok := st.streams.Session("5.1"); !ok {
		t.Fatal("session stopped while a viewer was still on it")
	}

	// The phone stops heartbeating: it expires and the session is released.
	deadline := time.Now().Add(15 * time.Second)
	for {
		if _, ok := st.streams.Session("5.1"); !ok {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("session not released after the last viewer expired")
		}
		time.Sleep(200 * time.Millisecond)
	}
	if len(st.streams.Viewers()) != 0 {
		t.Errorf("viewers should be empty after expiry: %+v", st.streams.Viewers())
	}
}

// TestTunersBusy checks that a channel whose device has no free tuner is
// refused with a 409 listing what the tuners are locked to, that a tuner
// we are already streaming from is marked shared, and that a free tuner
// lets the channel start.
func TestTunersBusy(t *testing.T) {
	st := newTestStack(t, time.Minute, 0)
	api := st.api

	st.hdhr.setStatus([]hdhomerun.TunerStatus{
		{Resource: "tuner0", VctNumber: "9.1", VctName: "OTHER", TargetIP: "10.0.0.9"},
		{Resource: "tuner1", VctNumber: "11.1", VctName: "OTHER2", TargetIP: "10.0.0.8"},
	})
	res, body := postJSON(t, api.URL+"/api/watch", map[string]any{"channel": "5.1"})
	if res.StatusCode != http.StatusConflict {
		t.Fatalf("busy watch status = %d: %s", res.StatusCode, body)
	}
	var busy struct {
		Code   string           `json:"code"`
		Tuners []tuner.TunerUse `json:"tuners"`
	}
	_ = json.Unmarshal(body, &busy)
	if busy.Code != "tuners_busy" || len(busy.Tuners) != 2 || busy.Tuners[0].Channel != "9.1" || busy.Tuners[0].Shared {
		t.Fatalf("busy body = %s", body)
	}
	// The plain playlist route gets the same answer.
	res, _ = http.Get(api.URL + "/api/channels/5.1/stream/index.m3u8")
	res.Body.Close()
	if res.StatusCode != http.StatusConflict {
		t.Fatalf("busy playlist status = %d", res.StatusCode)
	}

	// One tuner frees up: the channel starts.
	st.hdhr.setStatus([]hdhomerun.TunerStatus{
		{Resource: "tuner0", VctNumber: "9.1", VctName: "OTHER", TargetIP: "10.0.0.9"},
		{Resource: "tuner1"},
	})
	res, body = postJSON(t, api.URL+"/api/watch", map[string]any{"channel": "5.1", "viewerId": "tv"})
	if res.StatusCode != 200 {
		t.Fatalf("watch after free status = %d: %s", res.StatusCode, body)
	}

	// Now the device reports both tuners locked, one of them to our 5.1.
	// Joining 5.1 needs no tuner, and a busy answer for another channel
	// marks 5.1 as shared.
	st.hdhr.setStatus([]hdhomerun.TunerStatus{
		{Resource: "tuner0", VctNumber: "9.1", VctName: "OTHER", TargetIP: "10.0.0.9"},
		{Resource: "tuner1", VctNumber: "5.1", VctName: "TEST-HD", TargetIP: "127.0.0.1"},
	})
	res, body = postJSON(t, api.URL+"/api/watch", map[string]any{"channel": "5.1", "viewerId": "phone"})
	if res.StatusCode != 200 {
		t.Fatalf("join shared status = %d: %s", res.StatusCode, body)
	}
	// 7.1 is DRM so it is refused before tuner selection; use the registry
	// directly for a non-DRM channel the lineup does not have a session for.
	_, err := st.reg.ResolveSource(context.Background(), "5.1", map[string]bool{})
	var eb *tuner.ErrTunersBusy
	if !errors.As(err, &eb) {
		t.Fatalf("expected busy from resolver, got %v", err)
	}
	var shared int
	for _, tu := range eb.Tuners {
		if tu.Shared {
			shared++
		}
	}
	if shared != 0 {
		t.Errorf("with no active sessions nothing should be shared: %+v", eb.Tuners)
	}
	_, err = st.reg.ResolveSource(context.Background(), "5.1", map[string]bool{"5.1": true})
	if !errors.As(err, &eb) {
		t.Fatalf("expected busy from resolver, got %v", err)
	}
	for _, tu := range eb.Tuners {
		if tu.Channel == "5.1" && !tu.Shared {
			t.Errorf("5.1 should be marked shared: %+v", eb.Tuners)
		}
	}
}

// TestViewerDeviceNames checks which name a viewer is shown with: one the
// person chose, else the device's own, else the browser description, else
// the User-Agent.
func TestViewerDeviceNames(t *testing.T) {
	st := newTestStack(t, time.Minute, time.Minute)
	join := func(body map[string]any, ua string) {
		t.Helper()
		b, _ := json.Marshal(body)
		req, _ := http.NewRequest("POST", st.api.URL+"/api/watch", bytes.NewReader(b))
		req.Header.Set("Content-Type", "application/json")
		if ua != "" {
			req.Header.Set("User-Agent", ua)
		}
		res, err := http.DefaultClient.Do(req)
		if err != nil {
			t.Fatal(err)
		}
		out, _ := io.ReadAll(res.Body)
		res.Body.Close()
		if res.StatusCode != 200 {
			t.Fatalf("watch %v = %d: %s", body, res.StatusCode, out)
		}
	}
	join(map[string]any{"channel": "5.1", "viewerId": "chosen", "name": "Den", "deviceName": "Fire TV", "client": "Chrome on Windows"}, "")
	join(map[string]any{"channel": "5.1", "viewerId": "tv", "deviceName": "Living Room Fire TV"}, "opendvr-tv/0.3.0")
	join(map[string]any{"channel": "5.1", "viewerId": "web", "client": "Pixel 8 · Chrome"}, "")
	join(map[string]any{"channel": "5.1", "viewerId": "bare"}, "Mozilla/5.0 (Macintosh; Intel Mac OS X 14.6; rv:131.0) Gecko/20100101 Firefox/131.0")
	want := map[string]string{"chosen": "Den", "tv": "Living Room Fire TV", "web": "Pixel 8 · Chrome", "bare": "Firefox on Mac"}
	for _, v := range st.streams.Viewers() {
		if w, ok := want[v.ID]; ok && v.Name != w {
			t.Errorf("viewer %s named %q, want %q", v.ID, v.Name, w)
		}
		delete(want, v.ID)
	}
	if len(want) != 0 {
		t.Fatalf("viewers missing: %v", want)
	}
}
